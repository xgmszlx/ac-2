#!/usr/bin/env python3
"""Build the final A/B table from the run directories.

    python3 tools/ab_summary.py [--md] [--dirs results/runs/ab_*]

For every run directory it (re)computes `metrics.json` with tools/eval_run.py and then
prints one row per run, plus a per-arm aggregate. `--md` emits a markdown table ready to
paste into REPORT_EXPLORB_TEB.md.

Why a separate summary instead of trusting ab_table.csv: the table written during the run
is produced by an earlier (and lenient) success criterion, and one arm was interrupted
mid-run. This script always recomputes from the九 CSVs, so the report cannot drift from
the evidence.
"""
from __future__ import print_function

import glob
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARMS = ['B0', 'B1', 'Ours', 'Ours_no_cov']
COLS = [
    ('arm', 'arm'), ('n_goal', 'goals'), ('n_reached', 'reached'),
    ('n_aborted', 'aborted'), ('n_cmd', 'cmd_vel'),
    ('path_len_m', 'path m'), ('robot_moved_m', 'net m'),
    ('coverage_m2', 'coverage m2'), ('ate_rmse_m', 'ATE m'),
    ('lost_s', 'lost s'), ('tracking_ok_pct', 'track ok %'),
    ('teb_ms', 'TEB ms'), ('success', 'all reached'),
]


def teb_mean(task):
    """Mean TEB solve time from the throttled [teb-solve] lines of that run."""
    log = os.path.join(ROOT, 'logs', '%s_sim.log' % task)
    val = ''
    if not os.path.exists(log):
        return val
    for line in open(log, errors='ignore'):
        if '[teb-solve]' in line and 'mean=' in line:
            try:
                val = line.split('mean=')[1].split('ms')[0].strip()
            except IndexError:
                pass
    return val


def arm_of(task):
    for a in sorted(ARMS, key=len, reverse=True):
        if task.startswith('ab_%s_' % a):
            return a
    return '?'


def write_generated(rows):
    """Write results/ab_table_generated.{md,csv} straight from the run metrics."""
    outdir = os.path.join(ROOT, 'results')
    md_path = os.path.join(outdir, 'ab_table_generated.md')
    csv_path = os.path.join(outdir, 'ab_table_generated.csv')
    keys = [k for k, _l in COLS]
    with open(csv_path, 'w', newline='') as f:
        import csv as _csv
        w = _csv.writer(f)
        w.writerow(['task'] + keys)
        for r in sorted(rows, key=lambda x: (x['arm'], x['task'])):
            w.writerow([r.get('task')] + [r.get(k, '') for k in keys])
    with open(md_path, 'w') as f:
        f.write('# A/B runs — generated by tools/ab_summary.py (do not edit by hand)\n\n')
        f.write('Source: every `results/runs/*/metrics.json` under the workspace. '
                'Regenerate with `python3 tools/ab_summary.py --md --agg`.\n\n')
        f.write('| task | arm | goals | reached | cmd_vel | path m | net m | coverage m2 | '
                'RPE m | ATE m | lost(inner) s | TEB ms |\n')
        f.write('|---|---|---|---|---|---|---|---|---|---|---|---|\n')
        for r in sorted(rows, key=lambda x: (x['arm'], x['task'])):
            f.write('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n' % (
                r.get('task'), r['arm'], r.get('n_goal', ''), r.get('n_reached', ''),
                r.get('n_cmd', ''), _f(r.get('path_len_m')), _f(r.get('robot_moved_m')),
                _f(r.get('coverage_m2')), _f(r.get('rpe_rmse_m'), 4),
                _f(r.get('ate_rmse_m'), 4), _f(r.get('lost_internal_s')),
                r.get('teb_ms') or '-'))
        # per-arm aggregate
        import collections
        by = collections.defaultdict(list)
        for r in rows:
            by[r['arm']].append(r)
        f.write('\n## per-arm mean\n\n| arm | n | RPE m | ATE m | path m | coverage m2 | lost inner s | TEB ms |\n')
        f.write('|---|---|---|---|---|---|---|---|\n')
        for arm in ARMS:
            rs = by.get(arm, [])
            if not rs:
                continue
            def mean(k, nd=4):
                v = []
                for x in rs:
                    val = x.get(k)
                    try:
                        v.append(float(val))
                    except (TypeError, ValueError):
                        continue
                return ('%.' + str(nd) + 'f') % (sum(v) / len(v)) if v else '-'
            f.write('| %s | %d | %s | %s | %s | %s | %s | %s |\n' % (
                arm, len(rs), mean('rpe_rmse_m'), mean('ate_rmse_m'), mean('path_len_m', 3),
                mean('coverage_m2', 2), mean('lost_internal_s', 2), mean('teb_ms', 1)))
    return md_path, csv_path


def main():
    want_md = '--md' in sys.argv
    pattern = os.path.join(ROOT, 'results', 'runs', 'ab_*')
    dirs = sorted(glob.glob(pattern))
    if not dirs:
        print('no ab_* run directories found')
        return 1

    rows = []
    for d in dirs:
        if not os.path.isdir(d):
            continue
        subprocess.call([sys.executable, os.path.join(ROOT, 'tools', 'eval_run.py'), d],
                        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        mpath = os.path.join(d, 'metrics.json')
        m = json.load(open(mpath)) if os.path.exists(mpath) else {}
        task = os.path.basename(d)
        row = dict(m)
        row.update(task=task, arm=arm_of(task), teb_ms=teb_mean(task))
        rows.append(row)

    gen = write_generated(rows)
    print('wrote %s' % gen[0])
    print('wrote %s' % gen[1])

    if '--agg' in sys.argv:
        import collections
        by = collections.defaultdict(list)
        for r in rows:
            by[r['arm']].append(r)
        print('| arm | n | reached mean | path m mean | coverage m2 mean | ATE m mean | TEB ms mean |')
        print('|---|---|---|---|---|---|---|')
        for arm in ARMS:
            rs = by.get(arm, [])
            if not rs:
                continue
            def mean(key, nd=3):
                vals = [float(x[key]) for x in rs if x.get(key) not in (None, '')]
                return ('%.' + str(nd) + 'f') % (sum(vals) / len(vals)) if vals else '-'
            print('| %s | %d | %s | %s | %s | %s | %s |' % (
                arm, len(rs), mean('n_reached', 2), mean('path_len_m'),
                mean('coverage_m2'), mean('ate_rmse_m'), mean('teb_ms')))
        return 0

    if want_md:
        print('| arm | goals | reached | aborted | cmd_vel | path m | net m | coverage m2 | '
              'ATE m | lost s | track ok pct | TEB ms | all reached |')
        print('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
        for r in rows:
            print('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (
                r['arm'], r.get('n_goal', ''), r.get('n_reached', ''), r.get('n_aborted', ''),
                r.get('n_cmd', ''), _f(r.get('path_len_m')), _f(r.get('robot_moved_m')),
                _f(r.get('coverage_m2')), _f(r.get('ate_rmse_m', 0), 3),
                _f(r.get('lost_s')), _f(r.get('tracking_ok_pct'), 1),
                r.get('teb_ms') or '-', 'yes' if r.get('success') else 'no'))
    else:
        for r in rows:
            print('%-28s arm=%-12s %s' % (r['task'], r['arm'],
                  ' '.join('%s=%s' % (k, r.get(k)) for k, _l in COLS[1:] if k != 'arm')))
    return 0


def _f(v, nd=2):
    try:
        return ('%.' + str(nd) + 'f') % float(v)
    except (TypeError, ValueError):
        return '-'


if __name__ == '__main__':
    sys.exit(main())
