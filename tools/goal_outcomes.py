#!/usr/bin/env python3
"""Per-waypoint outcome table across every run directory.

    python3 tools/goal_outcomes.py [--dirs results/runs/ab_*] [--md]

The orchestrator's point: a "four-arm comparison" is only meaningful if all four arms were
*able to plan* to the same waypoint. move_base reports that separately from tracking:

    status 3  SUCCEEDED  "Goal reached."
    status 4  ABORTED    "Failed to find a valid plan. Even after executing recovery behaviors."
    status 2  CANCELED   preempted by the next goal

so this script lists, for every dispatched goal in every run, which waypoint it was, what
move_base answered, and how long it took. Runs whose waypoint was aborted are counted as
*failed episodes for that waypoint*, never folded into an arrival average.

Outputs:
    results/goal_outcomes.csv    one row per (run, goal)
    results/goal_outcomes.md     the same as a markdown table + per-waypoint summary
"""
from __future__ import print_function

import csv
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATUS = {3: 'reached', 4: 'aborted(no plan)', 2: 'canceled(preempted)', 1: 'active', 0: 'pending'}


def arm_of(task):
    for a in ('Ours_no_cov', 'Ours', 'B1', 'B0'):
        if task.startswith('ab_%s_' % a):
            return a
    if task.startswith('p0verify'):
        return 'p0verify'
    if task.startswith('corr'):
        return 'corr'
    if task.startswith('lam_'):
        return 'lambda'
    return '?'


def read_rows(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return list(csv.DictReader(f))


def main():
    want_md = '--md' in sys.argv
    dirs = sorted(d for d in glob.glob(os.path.join(ROOT, 'results', 'runs', '*')) if os.path.isdir(d))
    rows = []
    for d in dirs:
        task = os.path.basename(d)
        if task in ('house1',):
            continue
        goals = [r for r in read_rows(os.path.join(d, 'goals.csv')) if r.get('kind') == 'goal']
        results = [r for r in read_rows(os.path.join(d, 'goals.csv')) if r.get('kind') == 'result']
        for i, g in enumerate(goals):
            r = results[i] if i < len(results) else {}
            st = r.get('status', '')
            try:
                st = int(float(st))
            except (TypeError, ValueError):
                st = -1
            rows.append(dict(
                task=task, arm=arm_of(task), goal=i + 1,
                x=('%.2f' % float(g.get('x', 0) or 0)),
                y=('%.2f' % float(g.get('y', 0) or 0)),
                t_goal=('%.1f' % float(g.get('t', 0) or 0)),
                t_result=('%.1f' % float(r.get('t', 0) or 0)) if r else '',
                status=st, outcome=STATUS.get(st, 'no result'),
                reason=(r.get('info') or '').strip()[:80]))

    out_csv = os.path.join(ROOT, 'results', 'goal_outcomes.csv')
    with open(out_csv, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=['task', 'arm', 'goal', 'x', 'y', 't_goal', 't_result',
                                          'status', 'outcome', 'reason'])
        w.writeheader()
        for r in rows:
            w.writerow(r)

    # per-waypoint summary: "was (x,y) reachable for every arm?"
    every = {}
    for r in rows:
        if r['arm'] == '?':
            continue
        key = (r['x'], r['y'])
        every.setdefault(key, {}).setdefault(r['arm'], []).append(r['outcome'])

    out_md = os.path.join(ROOT, 'results', 'goal_outcomes.md')
    with open(out_md, 'w') as f:
        f.write('# Per-waypoint outcomes (generated by tools/goal_outcomes.py)\n\n')
        f.write('One row per dispatched goal. `aborted(no plan)` means move_base could not\n'
                'find a path -- a *feasibility* failure, not a tracking failure.\n\n')
        f.write('## waypoint x arm\n\n| waypoint | ' + ' | '.join(['B0', 'B1', 'Ours', 'Ours_no_cov']) + ' |\n')
        f.write('|---|' + '---|' * 4 + '\n')
        for key in sorted(every):
            cells = []
            for arm in ('B0', 'B1', 'Ours', 'Ours_no_cov'):
                outs = every[key].get(arm, [])
                if not outs:
                    cells.append('-')
                else:
                    n_ok = sum(1 for o in outs if o == 'reached')
                    cells.append('%d/%d' % (n_ok, len(outs)))
            f.write('| (%s, %s) | %s |\n' % (key[0], key[1], ' | '.join(cells)))
        f.write('\n## all goals\n\n| task | arm | # | waypoint | t | status | outcome | reason |\n')
        f.write('|---|---|---|---|---|---|---|---|\n')
        for r in rows:
            f.write('| %s | %s | %d | (%s, %s) | %s | %s | %s | %s |\n' % (
                r['task'], r['arm'], r['goal'], r['x'], r['y'], r['t_goal'],
                r['status'], r['outcome'], r['reason']))

    if want_md:
        print(open(out_md).read())
    else:
        print('wrote %s' % out_csv)
        print('wrote %s' % out_md)
        print('%d goal rows over %d run dirs' % (len(rows), len(dirs)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
